"""
Data Analysis Agent — FastAPI Backend

Exposes a Server-Sent Events (SSE) endpoint that streams the PydanticAI agent's
reasoning, tool calls, tool results, and final answer to the client in real time.

Streaming strategy:
  - Text deltas are parsed on-the-fly to extract <thinking> tags (see ThinkingStreamParser).
  - Tool calls emit a synthetic "thinking" block derived from their arguments when no
    native thinking is available (e.g. OpenAI models).
  - Native ThinkingPartDelta events (e.g. Anthropic extended thinking) take priority
    and suppress the synthetic fallback.

SSE event types emitted:
  - "thinking"    : reasoning content (native or synthetic)
  - "tool_call"   : tool invocation with name and arguments
  - "tool_result" : tool output, with optional Plotly file path
  - "text"        : final answer delta
  - "done"        : signals end of stream
  - "error"       : unexpected error during generation
"""

