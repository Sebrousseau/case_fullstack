def load_datasets(data_dir: str = "data") -> tuple[dict[str, pd.DataFrame], str]:
    """
    Load all CSV files from the data directory into in-memory DataFrames.

    Returns:
        datasets: mapping of sanitized dataset name → DataFrame
        dataset_info: human-readable summary injected into the agent's system prompt
    """
    data_path = Path(data_dir)
    if not data_path.exists():
        data_path.mkdir(parents=True, exist_ok=True)
        return {}, "No datasets available."

    datasets: dict[str, pd.DataFrame] = {}
    info_lines: list[str] = []

    for csv_file in sorted(data_path.glob("*.csv")):
        # Sanitize filename to a valid SQL table name
        name = re.sub(r"[^a-zA-Z0-9_]", "_", csv_file.stem).strip("_").lower()
        df = pd.read_csv(csv_file)
        datasets[name] = df
        cols = ", ".join(df.columns.tolist())
        info_lines.append(
            f"- **{name}** ({df.shape[0]} rows, {df.shape[1]} columns)\n"
            f"  Columns: {cols}"
        )

    if not info_lines:
        return {}, "No datasets available."

    return datasets, "\n".join(info_lines)


# Datasets are loaded once at startup and shared across requests.
# A server restart is required to pick up new CSV files.
datasets, dataset_info = load_datasets()
agent = create_agent(dataset_info)

