# ---------------------------------------------------------------------------
# SSE helper
# ---------------------------------------------------------------------------

def sse(event_type: str, data: dict) -> str:
    """Format a dict as a Server-Sent Event data line."""
    payload = json.dumps({"type": event_type, **data}, ensure_ascii=False)
    return f"data: {payload}\n\n"

# ---------------------------------------------------------------------------
# Thinking tag stream parser
# ---------------------------------------------------------------------------

class ThinkingStreamParser:
    """
    Parses <thinking>...</thinking> tags on-the-fly from a character stream.

    OpenAI models do not emit native ThinkingPartDelta events. Instead, the
    system prompt instructs the model to wrap its reasoning in <thinking> tags
    within the text stream. This parser separates those tags from the visible
    answer as the stream arrives, without waiting for the full response.

    Usage:
        parser = ThinkingStreamParser()
        for chunk in stream:
            for kind, content in parser.feed(chunk):
                emit(kind, content)  # kind is "thinking" or "text"
        for kind, content in parser.flush():
            emit(kind, content)      # flush any remaining buffered content
    """

    def __init__(self):
        self._buffer = ""
        self._in_thinking = False

    def feed(self, delta: str) -> list[tuple[str, str]]:
        """
        Feed a text delta and return (kind, chunk) pairs immediately emittable.

        A small tail of the buffer is always held back to handle tags that span
        chunk boundaries (e.g. "<think" in one chunk, "ing>" in the next).
        """
        results = []
        self._buffer += delta

        while self._buffer:
            if self._in_thinking:
                end = self._buffer.find("</thinking>")
                if end != -1:
                    # Emit everything up to the closing tag as thinking content
                    if end > 0:
                        results.append(("thinking", self._buffer[:end]))
                    self._buffer = self._buffer[end + len("</thinking>"):]
                    self._in_thinking = False
                else:
                    # Hold back the last 11 chars in case "</thinking>" spans chunks
                    safe = len(self._buffer) - 11
                    if safe > 0:
                        results.append(("thinking", self._buffer[:safe]))
                        self._buffer = self._buffer[safe:]
                    break
            else:
                start = self._buffer.find("<thinking>")
                if start != -1:
                    # Emit text before the opening tag, then switch to thinking mode
                    if start > 0:
                        results.append(("text", self._buffer[:start]))
                    self._buffer = self._buffer[start + len("<thinking>"):]
                    self._in_thinking = True
                else:
                    # Hold back the last 10 chars in case "<thinking>" spans chunks
                    safe = len(self._buffer) - 10
                    if safe > 0:
                        results.append(("text", self._buffer[:safe]))
                        self._buffer = self._buffer[safe:]
                    break

        return results

    def flush(self) -> list[tuple[str, str]]:
        """
        Flush any content remaining in the buffer at end of stream.

        Called once after the stream ends to ensure no content is lost.
        Unclosed <thinking> tags are emitted as thinking content.
        """
        results = []
        if self._buffer:
            kind = "thinking" if self._in_thinking else "text"
            results.append((kind, self._buffer))
            self._buffer = ""
        return results


