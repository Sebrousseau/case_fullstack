@app.post("/api/chat")
async def chat(request: ChatRequest):
    """
    Stream the agent's response as Server-Sent Events.

    The generator iterates over PydanticAI's run_stream_events() and maps each
    event type to one or more SSE messages. Deduplication sets prevent duplicate
    tool_call / tool_result events that can occur when both FunctionToolCallEvent
    and PartStartEvent fire for the same tool invocation.
    """
    async def generate():
        context = AgentContext(datasets=datasets, dataset_info=dataset_info)

        # Track emitted IDs to avoid sending duplicate events for the same call
        emitted_tool_calls: set[str] = set()
        emitted_tool_results: set[str] = set()

        # Set to True once a native ThinkingPartDelta is received, which disables
        # the synthetic thinking fallback for the rest of the response.
        has_real_thinking = False

        try:
            parser = ThinkingStreamParser()

            async for event in agent.run_stream_events(request.question, deps=context):

                # --- End of generation ---
                if isinstance(event, AgentRunResultEvent):
                    # Flush any content still buffered in the parser
                    for kind, chunk in parser.flush():
                        if chunk.strip():
                            yield sse(kind, {"content": chunk})
                    yield sse("done", {"content": ""})

                # --- Tool call (rich event with full args) ---
                elif isinstance(event, FunctionToolCallEvent):
                    call_id = event.part.tool_call_id
                    if call_id and call_id in emitted_tool_calls:
                        continue
                    try:
                        args = event.part.args_as_dict()
                    except Exception:
                        args = {}

                    # Skip early events emitted before args are fully streamed
                    if not args:
                        continue

                    if call_id:
                        emitted_tool_calls.add(call_id)

                    # Emit a synthetic thinking block derived from tool arguments.
                    # This gives users visibility into the agent's intent when the
                    # underlying model does not support native thinking output.
                    if not has_real_thinking:
                        thinking_lines = []
                        if "description" in args:
                            thinking_lines.append(args["description"])
                        if "sql" in args:
                            thinking_lines.append(f"SQL query: {args['sql']}")
                        if "title" in args:
                            thinking_lines.append(f"Visualization: {args['title']}")
                        if thinking_lines:
                            yield sse("thinking", {"content": "\n".join(thinking_lines)})

                    yield sse("tool_call", {
                        "tool": event.part.tool_name,
                        "args": args,
                        "call_id": call_id,
                    })

                # --- Part start (handles tool calls from providers using PartStartEvent) ---
                elif isinstance(event, PartStartEvent):
                    part = event.part
                    if isinstance(part, ToolCallPart):
                        call_id = part.tool_call_id
                        if call_id and call_id in emitted_tool_calls:
                            continue
                        try:
                            args = part.args_as_dict()
                        except Exception:
                            args = {}
                        if not args:
                            continue
                        if call_id:
                            emitted_tool_calls.add(call_id)
                        yield sse("tool_call", {
                            "tool": part.tool_name,
                            "args": args,
                            "call_id": call_id,
                        })

                # --- Text and thinking deltas ---
                elif isinstance(event, PartDeltaEvent):
                    delta = event.delta

                    if isinstance(delta, TextPartDelta) and delta.content_delta:
                        # Run through the parser to separate <thinking> from text
                        for kind, chunk in parser.feed(delta.content_delta):
                            yield sse(kind, {"content": chunk})

                    elif isinstance(delta, ThinkingPartDelta) and delta.content_delta:
                        # Native thinking (e.g. Anthropic extended thinking).
                        # Mark as real so the synthetic fallback is suppressed.
                        has_real_thinking = True
                        yield sse("thinking", {"content": delta.content_delta})

                # --- Tool result ---
                elif isinstance(event, FunctionToolResultEvent):
                    call_id = event.tool_call_id
                    if call_id and call_id in emitted_tool_results:
                        continue

                    content = str(event.result.content)

                    # Detect Plotly HTML files saved by the visualize tool
                    plotly_file = None
                    if "Saved to:" in content:
                        match = re.search(r"Saved to: (output/[^\s]+)", content)
                        if match:
                            plotly_file = match.group(1)

                    if call_id:
                        emitted_tool_results.add(call_id)

                    yield sse("tool_result", {
                        "call_id": call_id,
                        "content": content[:500],  # truncate large results
                        "plotly_file": plotly_file,
                    })

        except Exception as e:
            from anyio import BrokenResourceError
            if isinstance(e, BrokenResourceError):
                # Client disconnected mid-stream — exit silently
                return
            yield sse("error", {"content": str(e)})

    return StreamingResponse(
        generate(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",  # disable Nginx response buffering
        },
    )

